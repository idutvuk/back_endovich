"""Знак зодиака по дате рождения. Хранить в БД не нужно — чистая функция."""

from datetime import date

# (месяц, день окончания знака), знак действует ДО этой даты включительно
_BOUNDS = [
    ((1, 19), "Козерог"),
    ((2, 18), "Водолей"),
    ((3, 20), "Рыбы"),
    ((4, 19), "Овен"),
    ((5, 20), "Телец"),
    ((6, 20), "Близнецы"),
    ((7, 22), "Рак"),
    ((8, 22), "Лев"),
    ((9, 22), "Дева"),
    ((10, 22), "Весы"),
    ((11, 21), "Скорпион"),
    ((12, 21), "Стрелец"),
]


def zodiac_sign(birth_date: date) -> str:
    key = (birth_date.month, birth_date.day)
    for bound, sign in _BOUNDS:
        if key <= bound:
            return sign
    return "Козерог"  # 22–31 декабря
